// Copies the typefaces the console uses out of node_modules into console/fonts and writes
// console/css/fonts.css, so the app never fetches fonts from the network.
// Runs after `npm install`. The output is generated, not committed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = path.join(root, 'console', 'fonts');
const sources = [
  ['@fontsource-variable/archivo', ['wdth.css']],
  ['@fontsource/ibm-plex-sans-kr', ['400.css', '500.css', '600.css']],
  ['@fontsource/ibm-plex-mono', ['latin-400.css', 'latin-500.css']],
];

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
let css = '/* Generated by desktop/scripts/fonts.mjs. Do not edit. */\n', files = 0, bytes = 0;
for (const [pkg, sheets] of sources) {
  const dir = path.join(root, 'node_modules', pkg);
  if (!fs.existsSync(dir)) { console.warn(`fonts: ${pkg} is not installed, skipping`); continue; }
  for (const sheet of sheets) {
    const text = fs.readFileSync(path.join(dir, sheet), 'utf8')
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .replace(/,\s*url\([^)]*\.woff\)\s*format\(['"]woff['"]\)/g, '')
      .replace(/url\(\.\/files\/([^)]+\.woff2)\)/g, (_m, name) => {
        const src = path.join(dir, 'files', name);
        fs.copyFileSync(src, path.join(out, name)); files++; bytes += fs.statSync(src).size;
        return `url(../fonts/${name})`;
      })
      .replace(/\s+/g, ' ');
    css += text.trim() + '\n';
  }
}
fs.writeFileSync(path.join(root, 'console', 'css', 'fonts.css'), css);
console.log(`fonts: ${files} files, ${(bytes / 1048576).toFixed(1)} MB`);
